// Builds lib/content/colegios.ts from the Ministry of Education's open directory (datos.gov.co,
// "MEN_ESTABLECIMIENTOS_EDUCATIVOS_PREESCOLAR_BÁSICA_Y_MEDIA"): the public schools of Barranquilla.
// Run once a year, when the Ministry publishes a new year: `node scripts/colegios.mjs`.
import { writeFileSync } from "node:fs";

const DATASET = "https://www.datos.gov.co/resource/cfw5-qzt5.json";
const BARRANQUILLA = "08001";

/** Words that stay lowercase inside a name. */
const SMALL = new Set(["de", "del", "la", "las", "los", "el", "y", "para", "e"]);
/** Small words that also stay lowercase right after "IED". */
const LEADING_SMALL = new Set(["de", "del", "para"]);
/** Acronyms that stay uppercase. */
const ACRONYMS = new Set(["CODEBA", "COLCARO", "COTEDIBA", "IEDCAH"]);

/** The directory drops most accents; these are put back so the folder names read well. */
const ACCENTS = Object.fromEntries(
  ("Alegría Álvarez América Américas Ángel Arcángel Betsabé Bilingüe Bolívar Católicas Cívica Concentración " +
    "Concepción Corazón Formación Fundación Galán García Germán Guzmán Jesús José López María Márquez Martí " +
    "Nicolás Obregón Paraíso Pedagógicas Presentación Río Rondón Sánchez Simón Sofía Suárez Técnica Técnico " +
    "Unión Llinás")
    .split(" ")
    .map((word) => [word.normalize("NFD").replace(/[\u0300-\u036f]/g, ""), word]),
);

const PREFIXES = [
  ["INSTITUCION EDUCATIVA DISTRITAL ", "IED "],
  ["INSTITUCION EDUCATIVA COMUNITARIA DISTRITAL ", "IE Comunitaria Distrital "],
];

/** `afterPrefix`: the name follows "IED …", so a leading "de" or "para" stays lowercase too. */
function titleCase(text, afterPrefix = false) {
  return text
    .split(" ")
    .map((word, i) => {
      if (ACRONYMS.has(word)) return word;
      const lower = word.toLocaleLowerCase("es");
      if ((i > 0 || (afterPrefix && LEADING_SMALL.has(lower))) && SMALL.has(lower)) return lower;
      const capital = lower.charAt(0).toLocaleUpperCase("es") + lower.slice(1);
      return ACCENTS[capital.normalize("NFD").replace(/[\u0300-\u036f]/g, "")] ?? capital;
    })
    .join(" ");
}

/** The word after it starts a proper name: "Escuela Normal Superior La Hacienda". */
const NORMAL = "Escuela Normal Superior la ";

function shortName(official) {
  // The directory mixes "INSTITUCION" and "INSTITUCIÓN" and has double spaces
  let name = official.replace(/\s+/g, " ").trim().replace(/^INSTITUCIÓN/, "INSTITUCION");
  for (const [long, short] of PREFIXES) {
    if (name.startsWith(long)) return short + titleCase(name.slice(long.length), true);
  }
  const title = titleCase(name);
  return title.startsWith(NORMAL) ? title.replace(NORMAL, "Escuela Normal Superior La ") : title;
}

async function latestYear() {
  const url = `${DATASET}?$select=max(a_o) as year&$where=cod_dane_municipio='${BARRANQUILLA}'`;
  const [{ year }] = await (await fetch(url)).json();
  return year;
}

const year = await latestYear();
const where = `cod_dane_municipio='${BARRANQUILLA}' AND a_o='${year}' AND sector='OFICIAL'`;
const rows = await (await fetch(`${DATASET}?$where=${encodeURIComponent(where)}&$limit=1000`)).json();

const schools = rows
  .map((r) => ({ dane: r.codigo_dane, name: shortName(r.nombre_establecimiento) }))
  .sort((a, b) => a.name.localeCompare(b.name, "es"));

const body = `/* ------------------------------------------------------------------ */
/*  Public schools of Barranquilla (${schools.length}), for the gallery upload.        */
/*  Generated by scripts/colegios.mjs from the Ministry of Education's  */
/*  directory on datos.gov.co, year ${year}. Do not edit by hand.             */
/* ------------------------------------------------------------------ */

export interface School {
  /** DANE code: unique and stable, used to check the choice on the server. */
  dane: string;
  /** Short name, also the name of the school's folder in Drive. */
  name: string;
}

export const SCHOOLS_YEAR = "${year}";

export const SCHOOLS: readonly School[] = [
${schools.map((s) => `  { dane: "${s.dane}", name: ${JSON.stringify(s.name)} },`).join("\n")}
];
`;

writeFileSync(new URL("../lib/content/colegios.ts", import.meta.url), body);
console.log(`${schools.length} colegios (${year})`);
